import {
  ZCODE_MCP_BROWSER_SCREENSHOT_CONTENT_INDICES_META_KEY,
  ZCODE_MCP_NODE_REPL_CUA_APP_META_KEY,
} from "@zcode/contracts/mcp";
import { isOfficialCuaImageRefText } from "@zcode/zcode-cua/frame-contract";
import { CUA_APP_ASSOCIATIONS_META_KEY } from "@zcode/zcode-cua/host-display-contract";
import type { NodeReplRunResult } from "@zcode/core/repl";
import type { CallToolResult } from "@modelcontextprotocol/server";

type EmbeddedContentBlock = CallToolResult["content"][number];

interface EmbeddedMcpResult {
  content: EmbeddedContentBlock[];
  isError?: boolean;
  structuredContent?: Record<string, unknown>;
  _meta?: Record<string, unknown>;
}

function parseEmbeddedMcpResult(value: string): EmbeddedMcpResult | undefined {
  const trimmed = value.trim();
  const json = trimmed.startsWith("=>") ? trimmed.slice(2).trim() : trimmed;
  if (!json.startsWith("{")) return undefined;
  try {
    const parsed = JSON.parse(json) as unknown;
    if (!parsed || typeof parsed !== "object") return undefined;
    const candidate = parsed as Record<string, unknown>;
    if (!Array.isArray(candidate.content)) return undefined;
    if (
      candidate.content.some(
        (block) => !block || typeof block !== "object" || typeof (block as { type?: unknown }).type !== "string",
      )
    ) {
      return undefined;
    }
    return {
      content: candidate.content as EmbeddedContentBlock[],
      ...(typeof candidate.isError === "boolean" ? { isError: candidate.isError } : {}),
      ...(candidate.structuredContent && typeof candidate.structuredContent === "object"
        ? { structuredContent: candidate.structuredContent as Record<string, unknown> }
        : {}),
      ...(candidate._meta && typeof candidate._meta === "object"
        ? { _meta: candidate._meta as Record<string, unknown> }
        : {}),
    };
  } catch {
    return undefined;
  }
}

/**
* For multiple observations with screenshots in a cell, only the **last** raster is given to the model.
 *
* The model adjusted two observations with screenshots in one cell, and the result included two pictures.
* The exact-raster gate pressed "Only one final raster is allowed per result" to reject the entire frame of atoms - the model did not get a single one.
 *
* "The latest one wins" is originally the established semantics of producer: coordinates are only valid for the latest raster
* (zcode-cua's frame-pixel-latest-only test is this contract), old frames have no use value for the model.
* So the last image/authority pair is retained here and the earlier one is discarded, which is consistent with the contract and does not relax the access control——
* Really having two different rasters active at the same time is still not allowed.
 *
* Only CUA's "image + adjacent authority" atomic pair is processed; images without authority (such as Browser Use screenshots) are not affected.
 */
function keepLatestCuaFrame(blocks: EmbeddedContentBlock[]): EmbeddedContentBlock[] {
  const pairStarts: number[] = [];
  blocks.forEach((block, index) => {
    if (block.type !== "image") return;
    const next = blocks[index + 1];
    if (next?.type === "text" && isOfficialCuaImageRefText(next.text)) pairStarts.push(index);
  });
  if (pairStarts.length <= 1) return blocks;
  const dropped = new Set(pairStarts.slice(0, -1).flatMap((start) => [start, start + 1]));
  return blocks.filter((_, index) => !dropped.has(index));
}

export function toMcpRunResult(run: NodeReplRunResult): CallToolResult {
  const textParts: string[] = [];
// After SDK results are written via a dedicated sink, the second copy cannot be parsed from the run.result/console log.
// Otherwise, the model's JSON.stringify will reduce the image base64 to ordinary text, destroying the image/image_ref adjacency relationship.
  const structuredResults = run.structuredResults ?? [];
  const embedded =
    structuredResults.length === 0 && !run.error && run.result !== undefined
      ? parseEmbeddedMcpResult(run.result)
      : undefined;
  const responseMeta = { ...run.responseMeta };
  for (const structured of structuredResults) {
    if (structured._meta) Object.assign(responseMeta, structured._meta);
  }
  if (embedded?._meta) Object.assign(responseMeta, embedded._meta);
// This key determines whether the core will download the original image to disk, and REPL code cannot be allowed to pass through.
// setResponseMeta fake source; only accepts the index generated by NodeReplSession based on the real screenshot payload.
  delete responseMeta[ZCODE_MCP_BROWSER_SCREENSHOT_CONTENT_INDICES_META_KEY];
//Same type treatment: The producer's application metadata determines which App's name and icon the tool card displays. it has
// `projectToHost` -> `nodeRepl.emitStructuredResult` reaches the merge loop above, and that API hangs on the model
// Visible sandbox globals - emit one copy in the cell to make the card claim to have operated other applications. So here
// Discard unconditionally and only accept run.cuaApp recorded directly from the CUA bridge response from the broker.
  delete responseMeta[CUA_APP_ASSOCIATIONS_META_KEY];
  delete responseMeta[ZCODE_MCP_NODE_REPL_CUA_APP_META_KEY];
  if (run.cuaApp) responseMeta[ZCODE_MCP_NODE_REPL_CUA_APP_META_KEY] = run.cuaApp;
// Anthropic compatible gateways (such as bigmodel MaaS) only parse the consecutive characters starting with tool_result.content
// image block, once text is encountered first, the subsequent images will be discarded. The model can only see the image_ref metadata but not the picture.
// (Actually measured [image]/[image,text] is visible, [text,image]/[text,image,text] is invisible).
// Arrange image before text to allow the image to reach the model stably; the order is free in the Anthropic specification.
// The images are therefore arranged continuously starting from content[0]. The image subscript is equal to the content subscript, and there is no need to do a +1 offset.
  const browserScreenshotContentIndices = run.browserScreenshotImageIndices;
  const structuredContent = keepLatestCuaFrame(
    structuredResults.flatMap((structured) => structured.content as EmbeddedContentBlock[]),
  );
  const structuredContentResult = [...structuredResults]
    .reverse()
    .find((structured) => structured.structuredContent !== undefined);
  const structuredIsError = structuredResults.some((structured) => structured.isError === true);
  if (run.error) {
// node_repl If message-only is used to hide the common MCP failure prefix, only consume
// The analysis link of the model result text cannot distinguish success from failure. Continue to return only structured error.message,
// Don't mix in error types, stacks, or pre-failure logs, and let the generic bridge project stable flags based on isError.
    textParts.push(run.error.message);
  } else {
    if (run.logs) textParts.push(run.logs);
    if (structuredResults.length === 0 && run.result !== undefined && !embedded) {
      textParts.push(`=> ${run.result}`);
    }
  }

  const content = [
    ...(run.error
      ? []
      : structuredResults.length > 0
        ? structuredContent
        : (run.images ?? []).map((image) => ({
            type: "image" as const,
            data: image.base64,
            mimeType: image.mimeType,
          }))),
    ...(structuredResults.length > 0
      ? // 结构化观察已携带截图；模型再次 emitImage 同一张图时，只保留结构化结果中的副本。
// Deduplication must be equal byte by byte: the original pixels of the screenshot and its frame_id binding are retained, and different pictures are still rejected by frame verification.
        (run.images ?? [])
          .filter(
            (image) =>
              !structuredContent.some(
                (block) =>
                  block.type === "image" &&
                  (block as { data?: string }).data === image.base64,
              ),
          )
          .map((image) => ({
            type: "image" as const,
            data: image.base64,
            mimeType: image.mimeType,
          }))
      : []),
    ...(embedded?.content ?? []),
    ...(textParts.length > 0 ? [{ type: "text" as const, text: textParts.join("\n") }] : []),
  ];

  return {
    content: content.length > 0 ? content : [{ type: "text" as const, text: "(no output)" }],
    ...(run.error || embedded?.isError || structuredIsError ? { isError: true } : {}),
    ...(structuredContentResult?.structuredContent !== undefined
      ? { structuredContent: structuredContentResult.structuredContent }
      : embedded?.structuredContent !== undefined
        ? { structuredContent: embedded.structuredContent }
        : {}),
    ...(Object.keys(responseMeta).length > 0 ||
    (run.images?.length ?? 0) > 0 ||
    structuredContent.some((block) => block.type === "image")
      ? {
          _meta: {
            ...responseMeta,
            ...((run.images?.length ?? 0) > 0 || structuredContent.some((block) => block.type === "image")
              ? { "zcode/nodeReplEmittedImage": true }
              : {}),
            ...(browserScreenshotContentIndices && browserScreenshotContentIndices.length > 0
              ? {
                  [ZCODE_MCP_BROWSER_SCREENSHOT_CONTENT_INDICES_META_KEY]:
                    browserScreenshotContentIndices,
                }
              : {}),
          },
        }
      : {}),
  };
}
