/**
* Hide subcommand `__zcode-dwf-child <entry path>`: sandbox process entry for dynamic workflow.
 *
* Reason for existence: SEA single-file binary **does not interpret Node CLI flags** - harness default
* The flags in `node --max-old-space-size=… <entry>` will fall into the CLI's strict parseArgs as they are, and the child process will report an error immediately.
* Exit, so every workflow run under SEA must fail. The revision method is the same as the official plugin host
* (`plugin-host-command.ts`): Bootstrap under SEA allows harness to re-exec the binary and bring the sub-command.
* `run.ts` is dispatched here **before** parseArgs.
 *
* payload no longer uses argv (Windows command line upper limit
* 32,767 characters), harness writes a self-contained entry file `<cwd>/.zcode/workflow-runs/<runId>.mjs`, argv
* The last bit is just its path. The entry file comes with childMain and payload. Here we only `import()` it and add the CLI process
* vm/readline/stdio injects the `start` it exports - this module therefore no longer depends on `@zcode/dynamic-workflow-runtime`**.
* The best-effort `v8.setFlagsFromString` for the heap limit has also been moved into the entry file along with the payload.
 */

import { resolve } from "node:path";
import { createInterface } from "node:readline";
import { pathToFileURL } from "node:url";
import { createContext, runInContext } from "node:vm";
import { ZCODE_DWF_CHILD_COMMAND } from "@zcode/contracts";
import type { RunContext } from "@zcode/shared-types";

export function isDwfChildInvocation(argv: readonly string[]): boolean {
  return argv[0] === ZCODE_DWF_CHILD_COMMAND;
}

/** Entry file export surface (generated by `renderChildEntry` of child-source.ts). */
interface ChildEntryModule {
  start?: (deps: {
    vm: { createContext: typeof createContext; runInContext: typeof runInContext };
    createInterface: typeof createInterface;
    stdin: NodeJS.ReadableStream;
    stdout: { write(chunk: string): unknown };
  }) => Promise<void>;
}

/**
* Run the sandbox process until the script terminates. `argv` is the remaining parameters after removing the subcommand name, and the **last bit** is the entry file path.
 *
* Must wait until the end before returning: the CLI entry will hang for 1s after `run()` returns and exit watchdog
* (`scheduleCliExitWatchdog` of shutdown.ts), returning early is equivalent to letting the watchdog forcefully exit the child process when the run just starts.
 */
export async function runDwfChildCommand(ctx: RunContext, argv: string[]): Promise<number> {
  const entryPath = argv[argv.length - 1];
  if (argv.length === 0 || entryPath === undefined) {
    ctx.stderr.write(`Usage: ${ZCODE_DWF_CHILD_COMMAND} <entry path>\n`);
    return 1;
  }

  try {
// Dynamically import a copy of the ESM on the disk (the same as the plugin-host-command.ts loading plugin entry). Entry file
// Determine by yourself that "it is not a process entry" (argv[1] is the subcommand name, not it), it will not start automatically, and call start from here.
    const entry = (await import(pathToFileURL(resolve(entryPath)).href)) as ChildEntryModule;
    if (typeof entry.start !== "function") {
      throw new Error(`workflow entry file exports no start(): ${entryPath}`);
    }
    await entry.start({
      vm: { createContext, runInContext },
      createInterface,
      stdin: ctx.stdin,
      stdout: ctx.stdout,
    });
    return 0;
  } catch (error) {
// stdout is the NDJSON channel of the parent process, and diagnosis can only go through stderr - the harness is attributed to the stderr of the child process
// "Exit without completion" failure (child.on("close") of harness.ts).
    const message = error instanceof Error ? error.message : String(error);
    ctx.stderr.write(`Workflow child failed: ${message}\n`);
    return 1;
  }
}
