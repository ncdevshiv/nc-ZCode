// @ts-nocheck
/**
* Shared vocabulary for the schema subsystem: our "emit" JSON Schema subset types, and validators
* Output violation model. {@link JsonSchema} here is not a generic JSON Schema - it
* Exactly corresponds to the set of keywords produced by {@link synthesizeAskSchemas}, and the validator only understands this subset.
 */

/** Any legal JSON value. Literals appearing in const/enum/default are expressed using it. */
export type JsonValue =
  | string
  | number
  | boolean
  | null
  | JsonValue[]
  | { [key: string]: JsonValue };

/** The JSON Schema base type tag we will emit. The `integer` validator is supported but will not be actively generated on the synthesis side. */
export type JsonSchemaType =
  | "string"
  | "number"
  | "integer"
  | "boolean"
  | "null"
  | "array"
  | "object";

/**
* The subset of JSON Schema we emit. Fields are a union of optional keywords: a specific schema will only use them
* A few related to its shape (e.g. object schema with properties/required/additionalProperties,
* and union uses enum or anyOf). The validator only processes keywords appearing here.
 */
export interface JsonSchema {
// structure
  type?: JsonSchemaType | JsonSchemaType[];
  const?: JsonValue;
  enum?: JsonValue[];
  anyOf?: JsonSchema[];
  // object
  properties?: Record<string, JsonSchema>;
  required?: string[];
  additionalProperties?: boolean | JsonSchema;
  // array / tuple
  items?: JsonSchema;
  prefixItems?: JsonSchema[];
  minItems?: number;
  maxItems?: number;
// string constraints
  minLength?: number;
  maxLength?: number;
  pattern?: string;
  format?: string;
// number constraints
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
  exclusiveMaximum?: number;
// annotation
  description?: string;
  default?: JsonValue;
// Recursive types: reference and definition tables
  $ref?: string;
  $defs?: Record<string, JsonSchema>;
}

/**
* The single violation generated by the validator is designed to be directly entered into the tool_result for repair: one per line, including
* JSON path, expected and got.
 */
export interface Violation {
/** JSON path to the location of the violation, in the form of `$`, `$.foo`, `$.items[0]`. */
  path: string;
/** A short description of the desired shape/value. */
  expected: string;
/** A short description of the actual value obtained. */
  got: string;
}

/** Synthetic side diagnostic code. 9001 Already occupied by facade-siting rule (see analysis/sites.ts). */
export const SCHEMA_DIAGNOSTIC_CODE = 9002;

/**
* Maximum number of union members. If it exceeds, it will be considered as a "sick wide union" and a diagnosis will be reported on the ask site.
 *
* Take 100: it can not only accommodate reasonable enumerations (common enumerations such as status codes and country codes are far lower than this), but also block
*Obviously an out-of-control type situation. Acts on the number of members of both literal union (→ enum) and general union (→ anyOf).
 *
* In reality, it is usually not the handwritten giant union that triggers it, but the checker expansion template literal type (template
* literal type) - for example `` `${Dir}-${Size}` `` will be expanded into all combinations
* Literal union, it will explode when several dimensions intersect.
 */
export const MAX_UNION_MEMBERS = 100;
