// @ts-nocheck
import { UNPHASED_ID } from "./constants.js";
import type { OrderEvent, PhaseInfo } from "./causality-order.js";
import { KIND_RANK, reduceOrdering, type OrderKind } from "./causality-reduce.js";
import type { CausalityGraph, Certainty, OrderEdge, Phase, Step } from "./causality-graph.js";

/**
* Phase view: The author marks the imposed grouping with `phase("name")`, and its **quotient** on the cause and effect diagram
 *
* The ontology of the cause-and-effect diagram remains unchanged - only two things are done here, both of which are mechanical rewrites of the completed diagram:
 *
* - **Cross-stage copy**: The step claimed by k>1 stages becomes k copies (`~` suffix id + `source` connection
* key, the same mechanism and separator as may-set lane copy), so that "each step has exactly one phase" full division
* established;
* - **Business Map**: After reduction, the step side is projected onto the stage pair according to the claiming relationship, and the same one is run after deduplication
 *    {@link reduceOrdering}。
 *
* The whole zero mark script here is an identity function: all three fields are absent, and the existing snapshot is unchanged byte by byte. This is not optimization;
* Contract - the view switching condition of the UI is "whether the stage vocabulary is present or not".
 *
* Separate module instead of stuffing causality-graph.ts: that file is already on max-lines, and the stage is it
* A layered view above, just as a cause and effect diagram is a layered view above a site diagram.
 */

/** Copy id separator: the same as may-set lane copy (the shape is like `ask#2~actor#1~phase#2` when the two expansions are superimposed). */
const COPY_SEPARATOR = "~";

/** Claim relationship: who belongs to which stage, and how certain the claim is. All press the **site id** key. */
interface PhaseClaims {
/** Site -> Claim its stage, and remove duplicates in issue order. */
  bySite: Map<string, string[]>;
/** `${site}|${phase}` -> Claim certainty within this phase. */
  certainty: Map<string, Certainty>;
/** Stage -> The clock position of the first member issue; the sort key of the business graph fact. */
  position: Map<string, number>;
/** `${site}|${phase}` -> The first/last issue position of the site in this phase (time feasibility determination). */
  firstIssue: Map<string, number>;
  lastIssue: Map<string, number>;
}

/** Input of the business graph: the step edge after reduction (the sink edge has been eliminated), and the certainty has been inherited by endpoints. */
export interface PhaseSourceFact {
  from: string;
  to: string;
  kind: OrderKind;
  certainty: Certainty;
/** Carry is the underlying kind before modification; carry is minimized and pressed to determine the strength of the witness. */
  carryOf?: Exclude<OrderKind, "carry">;
  /**
* The stage set in which the issue event that witnesses this fact is located (only the seq fact generated by the await barrier takes it; see
* `Fact.toPhases` of causality-graph.ts). To narrow the head end press {@link headPhasesOf}.
   */
  toPhases?: ReadonlySet<string>;
}

/**
* Which stages should the head end of an edge fall on: **If there is source information, take the intersection, if not, then fully expand it**.
 *
* The same rule must be used for copy rewriting and business map projection, otherwise `phaseEdges` and the step in the drill-down will talk about two different things.
* Story - This is the whole reason to tie two consumers to a function.
 *
* The intersection is equal to `toPhases` itself in practice (the witness phase of the barrier fact must be the claim phase of the head site), the intersection is written out
* This is to prevent upstream changes such as "stage being discarded/narrowed" from linking edges to non-existent stages.
 */
function headPhasesOf(claiming: readonly string[], toPhases: ReadonlySet<string> | undefined): string[] {
  if (toPhases === undefined) return [...claiming];
  const narrowed = claiming.filter((phase) => toPhases.has(phase));
  return narrowed.length > 0 ? narrowed : [...claiming];
}

/**
* Read the claim relationship from the issue event. Issue is the identity moment of step, so this trip is the entire attribution logic.
 *
* The certainty of each (site, stage) is deduced separately: there is an issue determined by the regional chain in this stage, and the
* step is not the target of the control side. Corresponds literally to `certaintyOf` of causality-graph.ts, just replacing "all
* issue" is replaced with "issue at this stage" - shared helper in preflight (top level) and gate (in loop + branch)
* When each copy is made, the certainty of the two copies can therefore be different, which is why the copies must be derived separately.
 */
export function collectPhaseClaims(
  events: readonly OrderEvent[],
  steps: ReadonlySet<string>,
  certainChain: (chain: readonly string[]) => boolean,
  controlled: ReadonlySet<string>,
): PhaseClaims {
  const bySite = new Map<string, string[]>();
  const position = new Map<string, number>();
  const firstIssue = new Map<string, number>();
  const lastIssue = new Map<string, number>();
  const certainSeen = new Set<string>();
// The same clock as causality-graph.ts: each issue event moves one grid, regardless of whether it falls on the step in the graph.
  let clock = 0;
  for (const event of events) {
    if (event.at !== "issue") continue;
    const at = clock;
    clock += 1;
    if (!steps.has(event.step)) continue;
    const claiming = bySite.get(event.step);
    if (claiming === undefined) bySite.set(event.step, [event.phase]);
    else if (!claiming.includes(event.phase)) claiming.push(event.phase);
    if (!position.has(event.phase)) position.set(event.phase, at);
    const key = `${event.step}|${event.phase}`;
    if (!firstIssue.has(key)) firstIssue.set(key, at);
    lastIssue.set(key, at);
    if (certainChain(event.regions)) certainSeen.add(key);
  }

  const certainty = new Map<string, Certainty>();
  for (const [site, claiming] of bySite) {
    for (const phase of claiming) {
      const key = `${site}|${phase}`;
      certainty.set(key, certainSeen.has(key) && !controlled.has(site) ? "always" : "maybe");
    }
  }
  return { bySite, certainty, firstIssue, lastIssue, position };
}

/**
* Add phase vocabulary to completed cause and effect diagram: copy, `Step.phase`, phase table, phase edges.
 *
* Runs **after** `expandMaySetLanes` (to claim the lane copies in batches), and is the same as "mechanical processing of finished drawings"
*Rewrite": The existing content of step sets, lanes, regions, and step sides will not be recalculated.
 */
export function projectPhaseGraph(
  graph: CausalityGraph,
  phases: readonly PhaseInfo[],
  claims: PhaseClaims,
  facts: readonly PhaseSourceFact[],
  sharesIteration: (a: string, b: string) => boolean,
): CausalityGraph {
  if (phases.length === 0) return graph; // 零标记 → 零词汇表，图逐字节不动

  const claimsOf = (siteId: string): string[] => claims.bySite.get(siteId) ?? [UNPHASED_ID];
  const certaintyOfClaim = (siteId: string, phase: string): Certainty =>
    claims.certainty.get(`${siteId}|${phase}`) ?? "maybe";

  /**
* Time feasibility: Can an edge a→b fall on the copy pair (a@P, b@Q).
   *
* Each stage copy **occupies a time position**, which is the fundamental difference between it and the may-set lane copy - the lane copy has the same rank
* Side-by-side, full expansion will not assert any order; staged copy full expansion will assert false order ("gate's bench settle in
* preflight's bench issue"). The information walk here is there: issues for each (site, stage)
* Location. Multiple ordering is a permitted direction, misordering is not.
   *
* Two channels, or relationships:
* - **Position**: b has at least one issue in Q that falls after a's first issue in P;
* - **Duplicate**: Both sites share a closed iteration area. This is not optional - the producer of round k feeds
* The copy of k+1 rounds is "in front" and is actually achievable (the lesson of the reduce-accumulator). get rid of it,
* Cross-stage loops carrying data will disappear entirely, and that is the only prohibited direction to create concurrency out of thin air.
   *
* Share the same `sharesIteration` with `realizableCarry` of causality-graph.ts: on the same relationship
* The same question cannot be answered once in two places.
   */
  const admits = (from: string, fromPhase: string, to: string, toPhase: string): boolean => {
    const firstFrom = claims.firstIssue.get(`${from}|${fromPhase}`);
    const lastTo = claims.lastIssue.get(`${to}|${toPhase}`);
    if (firstFrom === undefined || lastTo === undefined) return true; // 无位置可判：不拦
    return lastTo > firstFrom || sharesIteration(from, to);
  };
  /**
* Kind subject to time feasibility. `carry` is not included: its own realizability has been determined in `realizableCarry`,
* Moreover, what carry asserts is the "next round", and position comparison is meaningless to it. `fifo` is not included: lane rules have been decided
* It, and the two copies of the same site share lanes, are indeed FIFO ordered with each other.
   */
  const ADMITTED_KINDS = new Set<OrderKind>(["data", "control", "seq"]);

// --- 1. Cross-stage copy ------------------------------------------------------------------
// The copy is **both-run, not a candidate** - don't just change the analogy of may-set copy to maybe. The site really starts from
// The two callers issue each one (the shared helper runs once in preflight and gate), and both copies will be executed; each copy
//Certainty only reflects how certain the claim is at that stage, and does not mean "one of the two".
  //
// `region` and `repeat` are **site-level facts** (taken from the first issue of the site), deliberately not recalculated according to stages: the copy is
// For mechanical rewriting of the finished map, recalculating region ownership requires a copy of the region tree at each stage, which is another decision. so
// The gate copy of the bench carries the `region` and `stack` of the first issue of preflight - don’t make a decision without
// "Fix" it if possible.
  const copiesOf = new Map<string, (Step & { phase: string })[]>();
  for (const step of graph.steps) {
    const siteId = step.source ?? step.id;
    const claiming = claimsOf(siteId);
    if (claiming.length < 2) continue;
    copiesOf.set(
      step.id,
      claiming.map((phase) => ({
        ...step,
        certainty: weakest([step.certainty, certaintyOfClaim(siteId, phase)]),
        id: `${step.id}${COPY_SEPARATOR}${phase}`,
        phase,
// `source` is the site id actually reported at runtime, **only set once**: the lane copy has been brought, so it will be used.
        source: siteId,
      })),
    );
  }

  const steps: Step[] = graph.steps.flatMap((step) => {
    const copies = copiesOf.get(step.id);
    if (copies !== undefined) return copies;
// k = 1: The claim is unique, so the certainty of this stage is literally equal to step itself (all issues are in
// at this stage), no need to overwrite.
    return [{ ...step, phase: claimsOf(step.source ?? step.id)[0] as string }];
  });

// --- 2. Edge rewriting: mirroring the mechanism of expandMaySetLanes -----------------------------------------
  const stepById = new Map(graph.steps.map((step) => [step.id, step]));
  const siteOf = (id: string): string => {
    const step = stepById.get(id);
    return step === undefined ? id : (step.source ?? step.id);
  };
//The source information of the fact is indexed by **site pair** (the fact exists before two copies, and there is only one for each ordered pair), so
// The edge copied by the lane is first converted back to the site and then checked.
  const provenance = new Map<string, ReadonlySet<string>>();
  for (const fact of facts) {
    if (fact.toPhases !== undefined) provenance.set(`${fact.from}|${fact.to}`, fact.toPhases);
  }

  const endpointsOf = (
    id: string,
    toPhases?: ReadonlySet<string>,
  ): { certainty: Certainty; id: string; lane?: string; phase: string }[] => {
    const copies = copiesOf.get(id);
    if (copies !== undefined) {
      const heads = new Set(headPhasesOf(claimsOf(siteOf(id)), toPhases));
      return copies
        .filter((copy) => heads.has(copy.phase))
        .map((copy) => ({
          certainty: copy.certainty,
          id: copy.id,
          lane: copy.lane,
          phase: copy.phase,
        }));
    }
    const step = stepById.get(id);
    return [
      {
        certainty: step?.certainty ?? "maybe",
        id,
        lane: step?.lane,
        phase: claimsOf(siteOf(id))[0] as string,
      },
    ];
  };

  const edges: OrderEdge[] = [];
  for (const edge of graph.edges) {
// Neither end is a copy → leave as is. This early retirement is also a structural guarantee of "the zero mark is unchanged byte by byte": a single endpoint pair
// Never pass any of the following rules.
    if (!copiesOf.has(edge.from) && !copiesOf.has(edge.to)) {
      edges.push(edge);
      continue;
    }
    const fromSite = siteOf(edge.from);
    const toSite = siteOf(edge.to);
// The tail is not narrowed by provenance (the settle event does not have a stage), but the tail is also subject to time feasibility constraints**——
// This is where the trailing pseudo-edge (the copy comes before the ask that produces its own arguments) ends up.
    const pairs: { certainty: Certainty; from: string; to: string }[] = [];
    const admitted: typeof pairs = [];
    for (const tail of endpointsOf(edge.from)) {
      for (const head of endpointsOf(edge.to, provenance.get(`${fromSite}|${toSite}`))) {
// fifo matches by lane and expands the same rule as the lane. Stage copies at the same site share lanes, so the
// fifo edges survive - that's right: two emits from a site are indeed FIFO ordered with each other.
        if (edge.kind === "fifo" && tail.lane !== head.lane) continue;
// The same copy is copied to itself: This is true only when the original edge is originally the self edge (the copy IDs of different sites cannot be equal),
//So this is writing down the invariants, not the branches that have been reached in the corpus.
        if (tail.id === head.id && edge.from !== edge.to) continue;
        const pair = {
          certainty: weakest([edge.certainty, tail.certainty, head.certainty]),
          from: tail.id,
          to: head.id,
        };
        pairs.push(pair);
        if (!ADMITTED_KINDS.has(edge.kind) || admits(fromSite, tail.phase, toSite, head.phase)) {
          admitted.push(pair);
        }
      }
    }
// All blocked → Return to full expansion, the same posture as {@link headPhasesOf}: a real sequence is nowhere
// It is achievable, which means that the position judgment misleads us, and silently deleting a real sequence is creating concurrency out of thin air.
    for (const pair of admitted.length > 0 ? admitted : pairs) {
      edges.push({ ...edge, ...pair });
    }
  }

// --- 3. Stage table: Stages with members, unphased is ranked first ----------------------------------------
  const members = new Set<string>(steps.map((step) => step.phase as string));
  const phaseList: Phase[] = [];
  if (members.has(UNPHASED_ID)) phaseList.push({ id: UNPHASED_ID });
  for (const phase of phases) {
// Stages with zero members are discarded (may-set narrowing may take away all steps of a certain stage) - empty nodes have no home to point to.
    if (!members.has(phase.id)) continue;
    phaseList.push({ id: phase.id, loc: phase.loc, name: phase.name });
  }
  const live = new Set(phaseList.map((phase) => phase.id));

// --- 4. Business map: calculated based on the claiming relationship and does not rely on the materialization of the copy ------------------------------------
  const quotient: PhaseSourceFact[] = [];
  for (const fact of facts) {
// Same rules as copy rewriting: head end narrowing ({@link headPhasesOf}) + time feasibility ({@link admits}),
// And it also only takes effect when at least one end is copied. Two consumers cannot each tell a story - `phaseEdges` and drill-down
// step must be talking about the same thing.
    const tails = claimsOf(fact.from);
    const heads = headPhasesOf(claimsOf(fact.to), fact.toPhases);
    const copied = tails.length > 1 || claimsOf(fact.to).length > 1;
    const gated = copied && ADMITTED_KINDS.has(fact.kind);
    const pairs: { from: string; to: string }[] = [];
    const admitted: typeof pairs = [];
    for (const from of tails) {
      for (const to of heads) {
        pairs.push({ from, to });
        if (!gated || admits(fact.from, from, fact.to, to)) admitted.push({ from, to });
      }
    }
    for (const { from, to } of admitted.length > 0 ? admitted : pairs) {
      if (!live.has(from) || !live.has(to)) continue;
// There is no picture in the order within the stage; the carry within the stage is the drawing method of "the entire cycle lives in one stage", leaving it as a self-loop.
      if (from === to && fact.kind !== "carry") continue;
      quotient.push({
        certainty: fact.certainty,
        from,
        kind: fact.kind,
        to,
        ...(fact.carryOf === undefined ? {} : { carryOf: fact.carryOf }),
      });
    }
  }

  const position = (id: string): number => claims.position.get(id) ?? 0;
  const deduped = dedupePhaseFacts(quotient).sort(
    (a, b) =>
      position(a.from) - position(b.from) ||
      position(a.to) - position(b.to) ||
      a.kind.localeCompare(b.kind),
  );
// The stage edge does not carry `exact`: that is the taint witness bit of the data edge, which is not defined in the quotient.
  const phaseEdges: OrderEdge[] = reduceOrdering(deduped).map((fact) => ({
    certainty: fact.certainty,
    from: fact.from,
    kind: fact.kind,
    to: fact.to,
  }));

  const sink = graph.sink;
  return {
    edges,
    lanes: graph.lanes,
    phaseEdges,
    phases: phaseList,
    regions: graph.regions,
    steps,
// The phase-level sink edge does not appear in the graph (the UI is derived from the phase of the fedBy step), but fedBy itself has to follow the copy.
    ...(sink === undefined
      ? {}
      : { sink: { fedBy: sink.fedBy.flatMap((id) => endpointsOf(id).map((end) => end.id)) } }),
  };
}

/**
* Each ordered phase pair leaves one fact: kind takes the strongest ({@link KIND_RANK}), certainty maybe-wins——
* **Verbatim mirroring step-level `dedupeFacts`**, consistency first ("Any always witness is always" in business
*More accurate semantics).
 */
function dedupePhaseFacts(facts: readonly PhaseSourceFact[]): PhaseSourceFact[] {
  const byPair = new Map<string, PhaseSourceFact>();
  for (const fact of facts) {
    const key = `${fact.from}|${fact.to}`;
    const existing = byPair.get(key);
    if (existing === undefined) {
      byPair.set(key, { ...fact });
      continue;
    }
    if (KIND_RANK[fact.kind] > KIND_RANK[existing.kind]) existing.kind = fact.kind;
    if (existing.carryOf === undefined && fact.carryOf !== undefined) existing.carryOf = fact.carryOf;
    if (fact.certainty === "maybe") existing.certainty = "maybe";
  }
  return [...byPair.values()];
}

function weakest(values: readonly Certainty[]): Certainty {
  return values.includes("maybe") ? "maybe" : "always";
}
