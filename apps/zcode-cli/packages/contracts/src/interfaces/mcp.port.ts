export interface McpToolDescriptor {
  serverName: string;
  toolName: string;
  name?: string;
  description?: string;
  timeoutMs?: number;
  inputSchema: JsonSchema;
  outputSchema?: JsonSchema;
  annotations?: McpToolAnnotations;
  /**
* The results of this tool are **trustworthy enough to change the interface** accordingly: from `type: "http"` and declared
* MCP server with `auth.type = zcode_official`.
   *
* The only use is for structured identification in trust results (`error_code` for depleted credit/no plan). The criterion is "Who produced the result?"
* Instead of "who is the plug-in":
* - http: Response comes from ZCode backend. The survival of the connection means that each request has passed the origin verification and failed closed.
* Even if the third-party plug-in declares official authentication, it can only send the request to the real ZCode, and the response body is not written by it;
* - stdio: The result is generated by the plug-in process itself and can be forged at will, so **not set**.
   *
* Deliberately **not** judge by "whether the plug-in comes from the official marketplace": that will make unofficial installation sources (including local self-test and
* The official plugin of zcode-plugins-test) is invalid, and it is not a real barrier - see `@zcode/shared` for details
   * `isOfficialMcpOriginTrusted`。
   */
  official?: boolean;
}

