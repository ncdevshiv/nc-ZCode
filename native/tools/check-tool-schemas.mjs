#!/usr/bin/env node
// Tool **Parameter entry** Reconciliation: Whether the parameters declared by TS to the model are really recognized by the Rust native tools.
//
// Why do this separately: The parity table proves "the tool exists", and the schema table proves "the tool exists and the parameters are not silently ignored".
// The latter is the actual contact surface of the model - TS writes `-C`/`head_limit`/`offset`/`type`/`multiline` into
// When the model sees the schema, if Rust only recognizes a few of them, the call will be "successful" but the parameters will not be written. This type of inconsistency
// The reading code is incomplete (the Grep of `ENTRY 132` is generated by the base check field).
//
// Get the **runtime truth** on both sides:
// - Rust: `cargo run -p zcode-host --bin tool_contracts` (tool_definitions for the production registry);
// - TS: `builtInTools` of `core/dist/tool/handlers/index.js`, input JSON Schema of each entry.
// Differences must either be fixed in this round or registered with reasons in `tool-schemas.baseline.json`;
// New, unregistered TS→Rust missing parameters = gate failure. Entries in the baseline pointing to disappeared differences are also considered failures (anti-corrosion).
//
// Usage: pnpm exec tsx native/tools/check-tool-schemas.mjs [--json] [--self-test]

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const BASELINE = "native/tools/tool-schemas.baseline.json";

/** The fields on both sides of the schema in the entry have different histories. Try them one by one; if they are not found, they will explicitly fail instead of skipping. */
function schemaOf(entry, name) {
  const candidate =
    entry.inputJsonSchema ??
    entry.inputSchema ??
    entry.metadata?.inputJsonSchema??
    entry.metadata?.inputSchema;
  if (!candidate || typeof candidate.properties !== "object") {
    return { error: `${name}: input JSON Schema not found (entry shape changed)` };
  }
  return {
    properties: Object.keys(candidate.properties ?? {}),
    required: (candidate.required ?? []).filter((key) => typeof key === "string"),
  };
}

async function tsSchemas() {
  const index = pathToFileURL(
    join(root, "apps/zcode-cli/packages/core/dist/tool/handlers/index.js"),
  ).href;
  const module = await import(index);const entries = module.builtInTools ?? module.default?.builtInTools;
  if (!Array.isArray(entries)) throw new Error("builtInTools is not an array (the exported shape has changed)");
  const out = new Map();
  const problems = [];
  for (const entry of entries) {
    const name = entry.metadata?.name ?? entry.name;
    if (!name) {
      problems.push("A certain builtInTools entry does not have metadata.name");
      continue;
    }
    const schema = schemaOf(entry, name);
    if (schema.error) problems.push(schema.error);
    else out.set(name, schema);
  }
  return { schemas: out, problems };
}

function rustSchemas() {
  const stdout = execFileSync(
    "cargo",
    ["run", "-q", "-p", "zcode-host", "--bin", "tool_contracts"],
    { cwd: join(root, "native"), encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
  );
  const line = stdout
    .trim()
    .split("\n")
    .filter((row) => row.trim().startsWith("["))
    .pop();
  const rows = JSON.parse(line);
  const out = new Map();
  for (const row of rows)
    out.set(row.name, { properties: row.properties, required: row.required ?? [] });
  return out;
}

/** Pure function: `--self-test` directly feeds fake data to prove that the check can really bite. */
function diffTool(name, ts, rust, baseline) {
  const problems = [];
  const notes = [];
  const tsSet = new Set(ts.properties);
  const rustSet = new Set(rust.properties);
  const allowed = baseline[name]?.tsOnly ?? {};
  for (const key of tsSet) {
    if (rustSet.has(key)) continue;
    if (typeof allowed[key] === "string" && allowed[key].trim().length >= 12) continue;
    problems.push(
      typeof allowed[key] === "string"
        ? `${name}.${key}: The reason in baseline is too short (at least 12 words)`
        : `${name}.${key}: TS parameters declared to the model, not available on the Rust side (either implemented or registered with a reason)`,
    );
  }
  for (const key of Object.keys(allowed)) {
    if (!tsSet.has(key) || rustSet.has(key)) {problems.push(`${name}.${key}: baseline entry is rotten (TS no longer declares this parameter, or Rust has implemented it)`);
    }
  }
  for (const key of rustSet) if (!tsSet.has(key)) notes.push(`${name}.${key}: only on Rust side`);
  for (const key of ts.required ?? []) {
    if (!(rust.required ?? []).includes(key) && rustSet.has(key)) {
      problems.push(`${name}.${key}: TS required, Rust optional - constraints on both sides are inconsistent`);
    }
  }
  return { problems, notes };
}

function selfTest() {
  const baseline = { Foo: { tsOnly: { dropped: "Not needed on the R side, because this parameter is only valid in the cloud configuration" } } };
  const cases = [
    [
      "Missing parameters need to be reported",
      diffTool(
        "Foo",
        { properties: ["kept", "missing"], required: [] },
        { properties: ["kept"], required: [] },
        baseline,
      ).problems.some((problem) => problem.includes("Foo.missing")),
    ],
    [
      "Registered missing parameters are not reported",
      !diffTool(
        "Foo",
        { properties: ["dropped"], required: [] },
        { properties: [], required: [] },
        baseline,
      ).problems.some((problem) => problem.includes("dropped")),
    ],
    [
      "Registration reason is too short to report",
      diffTool(
        "Foo",
        { properties: ["dropped"], required: [] },
        { properties: [] },
        { Foo: { tsOnly: { dropped: "short" } } },
      ).problems.some((problem) => problem.includes("Too short")),
    ],
    [
      "Baseline rot needs to be reported",
      diffTool("Foo", { properties: [], required: [] }, { properties: [] }, baseline).problems.some(
        (problem) => problem.includes("rotten"),
      ),
    ],
    [
      "Report any inconsistencies required",
      diffTool(
        "Foo",
        { properties: ["a"], required: ["a"] },
        { properties: ["a"], required: [] },
        {},
      ).problems.some((problem) => problem.includes("required")),
    ],
    [
      "No report if the shape is the same",
      diffTool(
        "Foo",
        { properties: ["a"], required: ["a"] },{ properties: ["a"], required: ["a"] },
        {},
      ).problems.length === 0,
    ],
  ];
  const failures = cases.filter(([, ok]) => !ok).map(([label]) => label);
  console.log(
    failures.length === 0
      ? `[tool-schemas] self-test ok (${cases.length} positive and negative examples are as expected)`
      : `[tool-schemas] self-test FAILED: ${failures.join(" / ")}`,
  );
  process.exit(failures.length === 0 ? 0 : 1);
}

if (process.argv.includes("--self-test")) selfTest();

const baseline = JSON.parse(readFileSync(join(root, BASELINE), "utf8"));
const { schemas: ts, problems: shapeProblems } = await tsSchemas();
const rust = rustSchemas();
const problems = [...shapeProblems];
const notes = [];
let compared = 0;
for (const [name, schema] of ts) {
  const mine = rust.get(name);
  if (!mine) continue; // TS-only tools are handled by the boundary table of tool-parity and are not repeatedly registered here.
  compared += 1;
  const result = diffTool(name, schema, mine, baseline);
  problems.push(...result.problems);
  notes.push(...result.notes);
}

if (process.argv.includes("--json")) {
  console.log(JSON.stringify({ compared, problems, notes }, null, 2));
} else {
  console.log(`[tool-schemas] Reconciliation of ${compared} tools with the same name on both sides (TS declaration side vs Rust declaration side)`);
  for (const problem of problems) console.error(` ✗ ${problem}`);
  if (problems.length === 0) console.log("[tool-schemas] ok: No parameters declared by TS but ignored by Rust");
}
process.exit(problems.length === 0 ? 0 : 1);